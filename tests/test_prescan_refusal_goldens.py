"""LLR-RML.1.4 -- byte-identity characterization golden for the sidecar prescan refusals.

Provenance (LED .35): the 8 constants below were GENERATED by RUNNING the base `store.py`
(batch `2026-10-25-relmap-r1-batch`, base commit 25d69fe, `store.py` untouched) with
`.dev-flow/2026-10-25-relmap-r1-batch/evidence/inc3-golden-capture.py`; they were not typed.
They pin the text of 4 refusals (a short anchor, an alias, a 5,000-character anchor named at 40
characters plus an ellipsis, nesting depth 65) at the 2 call sites of the prescan: `MapStore.load`
and `MapStore._capped_side_graph` (called directly, because `git_diff` turns every refusal into
`None`).  `tests/test_ingestion_limits.py` asserts substrings and a length bound, NOT byte
identity: this file is the byte limb.  Moving the prescan to `mapper/yamlscan.py` must leave all
8 strings equal.
"""
from __future__ import annotations

import pytest

from mapper.store import MapStore, MapStoreError

MMD = "graph TD\n    a[raiz]\n"


def _nested_flow(n: int) -> str:
    text = "0"
    for _ in range(n):
        text = "{k: " + text + "}"
    return text


GOLDEN_SHORT_ANCHOR_LOAD = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'x')"
)
GOLDEN_SHORT_ANCHOR_SIDE = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'x')"
)
GOLDEN_ALIAS_LOAD = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'zz')"
)
GOLDEN_ALIAS_SIDE = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'zz')"
)
GOLDEN_LONG_ANCHOR_LOAD = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'gggggggggggggggggggggggggggggggggggggggg…')"
)
GOLDEN_LONG_ANCHOR_SIDE = (
    "could not read the card of m: YAML anchors and aliases are not allowed here (anchor 'gggggggggggggggggggggggggggggggggggggggg…')"
)
GOLDEN_DEPTH_65_LOAD = (
    'could not read the card of m: it nests deeper than the depth limit (64)'
)
GOLDEN_DEPTH_65_SIDE = (
    'could not read the card of m: it nests deeper than the depth limit (64)'
)

# (arm id, sidecar text, golden at load, golden at _capped_side_graph)
ARMS = [
    ("short_anchor", "a: &x 1\n", GOLDEN_SHORT_ANCHOR_LOAD, GOLDEN_SHORT_ANCHOR_SIDE),
    ("alias", "b: *zz\n", GOLDEN_ALIAS_LOAD, GOLDEN_ALIAS_SIDE),
    ("long_anchor", "a: &" + "g" * 5000 + " 1\n", GOLDEN_LONG_ANCHOR_LOAD, GOLDEN_LONG_ANCHOR_SIDE),
    ("depth_65", _nested_flow(65), GOLDEN_DEPTH_65_LOAD, GOLDEN_DEPTH_65_SIDE),
]


@pytest.mark.parametrize("arm,yml,golden_load,golden_side", ARMS, ids=[a[0] for a in ARMS])
def test_prescan_refusal_text_is_byte_identical(tmp_path, arm, yml, golden_load, golden_side):
    (tmp_path / "m.mmd").write_text(MMD, encoding="utf-8")
    (tmp_path / "m_nodos.yml").write_text(yml, encoding="utf-8")
    store = MapStore(tmp_path)
    with pytest.raises(MapStoreError) as at_load:
        store.load("m")
    with pytest.raises(MapStoreError) as at_side:
        store._capped_side_graph("m", MMD, yml)
    assert str(at_load.value) == golden_load
    assert str(at_side.value) == golden_side


def test_the_goldens_are_eight_call_site_strings():
    texts = [t for _, _, a, b in ARMS for t in (a, b)]
    assert len(texts) == 8
    assert all(t.startswith("could not read the card of m: ") for t in texts)
    assert GOLDEN_LONG_ANCHOR_LOAD.endswith("g" * 40 + "…')")
